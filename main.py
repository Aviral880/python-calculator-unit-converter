def add(a,b):
    return a+b

def subtract(a,b):
    return a-b

def multiply(a,b):
    return a*b

def divide(a,b):
    if b==0:
        return "Error: Cannot divide by zero!"
    return a/b

def km_to_miles(km):
    return km*0.621371

def celsius_to_fahrenheit(celsius):
    return (celsius*9/5)+32

def kg_to_pounds(kg):
    return round(kg*2.20462)

